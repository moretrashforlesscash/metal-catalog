"""Названия городов Казахстана: старые, разговорные, казахские и в падежах → как на биржах ставок.

normalize("в Карагу") → ("Караганда", None); normalize("Капчагай") → ("Алматы", "считаем до Алматы (~70 км)").
"""

import re

# города, по которым fa-fa отдаёт ставку Москва → город (проверено 2026-10-23)
KNOWN = ["Алматы", "Астана", "Шымкент", "Караганда", "Актобе", "Тараз", "Павлодар", "Усть-Каменогорск", "Семей",
         "Атырау", "Костанай", "Кызылорда", "Уральск", "Петропавловск", "Актау", "Темиртау", "Туркестан",
         "Кокшетау", "Талдыкорган", "Экибастуз", "Жезказган", "Балхаш", "Сатпаев", "Риддер", "Рудный"]

ALIASES = {
    "алма-ата": "Алматы", "алмата": "Алматы", "алма ата": "Алматы", "алмате": "Алматы",
    "нур-султан": "Астана", "нурсултан": "Астана", "нур султан": "Астана", "акмола": "Астана", "целиноград": "Астана",
    "чимкент": "Шымкент", "шимкент": "Шымкент",
    "карага": "Караганда", "карагандa": "Караганда",
    "актюбинск": "Актобе", "джамбул": "Тараз", "жамбыл": "Тараз",
    "усть-ка": "Усть-Каменогорск", "усть ка": "Усть-Каменогорск", "устька": "Усть-Каменогорск",
    "оскемен": "Усть-Каменогорск", "өскемен": "Усть-Каменогорск", "усть каменогорск": "Усть-Каменогорск",
    "семипалатинск": "Семей", "гурьев": "Атырау", "кустанай": "Костанай", "кызыл-орда": "Кызылорда",
    "орал": "Уральск", "петропавл": "Петропавловск", "шевченко": "Актау", "кокчетав": "Кокшетау",
    "талдык": "Талдыкорган", "джезказган": "Жезказган", "балкаш": "Балхаш", "лениногорск": "Риддер",
}
# нет на бирже — считаем до ближайшего крупного
NEAREST = {"конаев": ("Алматы", "~70 км"), "капчагай": ("Алматы", "~70 км"), "қонаев": ("Алматы", "~70 км"),
           "каскелен": ("Алматы", "~30 км"), "талгар": ("Алматы", "~30 км"), "есик": ("Алматы", "~50 км"),
           "косшы": ("Астана", "~20 км"), "сарань": ("Караганда", "~25 км"), "шахтинск": ("Караганда", "~50 км"),
           "аксу": ("Павлодар", "~50 км"), "степногорск": ("Кокшетау", "~180 км")}


def normalize(name):
    """Возвращает (город для расчёта, пояснение или None)."""
    s = re.sub(r"^(?:г\.?|город|в|во|до|из)\s+", "", name.strip().lower().replace("ё", "е"))
    s = s.strip(" .,")
    for k, v in ALIASES.items():
        if s == k or (len(k) >= 6 and s.startswith(k[:5])):
            return v, None
    for k, (v, dist) in NEAREST.items():
        if s.startswith(k[:5]):
            return v, f"{name.strip()} нет на бирже ставок — считаем до {v} ({dist} дальше)"
    for city in KNOWN:  # падежи: «Караганду», «Шымкента», «Астане» — по общему началу слова
        c = city.lower()
        if s == c or (len(s) >= 4 and (s.startswith(c[:max(4, len(c) - 2)]) or c.startswith(s))):
            return city, None
    return name.strip().capitalize(), None
